# The judge retries once, not the client default of five. call_with_timeout
# abandons its worker at the deadline now instead of waiting for it, so an
# abandoned judge call keeps running on its own: at five retries over two calls
# it would go on buying attempts the run has already thrown away. Same argument
# generation.py makes with GENERATION_MAX_RETRIES, arriving at a different
# number because the judge is not on the measured clock.
#
# One consequence worth knowing: the outer deadline is max_response_timeout_
# seconds for the whole of evaluate_with_judge, so this retry cannot rescue a
# call that TIMES OUT - we give up before the second attempt could finish. It
# buys back the fast failures, a 429 or a 502 returned immediately, which fit
# inside the window. max_response_timeout_seconds stays the ceiling for one
# evaluation.
JUDGE_MAX_RETRIES = 1


class JudgeScore(NamedTuple):
    """A single evaluator's verdict: score is 1-10, or -1 for "not measured".

    The return type of the three _evaluate_* functions. Coexists with, and is
    not a replacement for, the four-key dict evaluate_with_judge builds a few
    lines below — that dict is the task/global pair together, this is one
    side of it, and neither shape is what progress.jsonl stores.
    """

    score: int
    reasoning: str


def _evaluate_llm_judge(
    prompt: TestCaseResult | TempPrompt,
    candidate_response: str,
    judge_config: JudgeConfig,
    local_media_paths: list[str] | None = None,
) -> JudgeScore:
    """Execute evaluation using the judge LLM.

    Args:
        prompt: The TestCaseResult or TempPrompt containing prompt and criteria.
        candidate_response: The response text generated by the candidate.
        judge_config: JudgeConfig instance.
        local_media_paths: Optional local paths to media files attached as ground truth.

    Returns:
        A tuple of (score, reasoning) where score is 1-10 and reasoning is the judge's text explanation.
    """
    evaluation_template = judge_config.test_judge.evaluation_template
    sys_prompt = judge_config.test_judge.evaluation_system_prompt

    if not evaluation_template:
        return -1, "Error: Missing evaluation_template in judge_config."

    try:
        evaluation_prompt = evaluation_template.format(
            user_prompt=prompt.prompt,
            candidate_response=candidate_response,
            criteria=prompt.criteria,
        )
    except KeyError as exc:
        return -1, f"Error in evaluation template: missing field {exc}"
    except (IndexError, ValueError) as exc:
        # str.format raises three things, not one: IndexError for a positional
        # {} or {0}, ValueError for an unbalanced brace. A JSON example inside
        # the template is the common way to hit the second. Left uncaught they
        # reached the dispatcher's own except, which zeroes the global score
        # too - including one already computed and paid for. reasoning.py and
        # projectio.check_evaluation_template already catch all three.
        #
        # The "Error in evaluation template" prefix must stay byte-identical:
        # progress.is_failed_eval matches on it to make the event retryable.
        return -1, f"Error in evaluation template: {exc}"

    if local_media_paths:
        # Prepended, not appended: a provider without native file support
        # inlines the attachments AHEAD of the whole prompt, so a note in the
        # tail would announce a file the judge read several thousand tokens
        # earlier. Head position puts it right after the content it describes.
        names = ", ".join(os.path.basename(path) for path in local_media_paths)
        many = len(local_media_paths) > 1
        subject = "files for the test are" if many else "file for the test is"
        evaluation_prompt = (
            f"[SYSTEM NOTE]: The original {subject} attached ({names}). "
            f"Use {'them' if many else 'it'} as ground truth to verify the "
            "candidate's response.\n\n"
        ) + evaluation_prompt

    provider = judge_config.test_judge.provider
    model_name = judge_config.test_judge.model
    judge_temp = judge_config.test_judge.temperature
    thinking = judge_config.test_judge.thinking
    disable_safety = judge_config.test_judge.disable_safety

    try:
        result = get_llm_response(
            provider=provider,
            model_name=model_name,
            system_instruction=sys_prompt,
            user_prompt=evaluation_prompt,
            local_media_paths=local_media_paths,
            temp=judge_temp,
            thinking=thinking,
            response_mime_type="application/json",
            disable_safety=disable_safety,
            max_response_timeout_seconds=judge_config.max_response_timeout_seconds,
            max_retries=JUDGE_MAX_RETRIES,
        )
        parsed = parse_json_object(result.text)
        if parsed is None:
            return -1, f"Error: LLM response did not parse as a dict: {result.text}"

        reasoning = parsed.get("reasoning", "")
        raw_score = parsed.get("score")
        try:
            score = int(raw_score)
        except (TypeError, ValueError):
            return -1, f"Error: LLM response 'score' field is missing or not numeric: {raw_score!r}"

        # A real score from the judge, only out of range: clamp it exactly like
        # _evaluate_assert/_evaluate_similarity do, rather than treating a
        # badly-formed real score as a system error.
        score = max(1, min(10, score))
        return score, str(reasoning)
    except Exception as exc:
        return -1, f"LLM evaluation failed: {exc}"


def embed_with_similarity_judge(text: str, judge_config: JudgeConfig) -> list[float]:
    """Embed text with the project's similarity_judge, under the judge budget.

    The one embedding call every evaluator makes, so all of them retry and
    time out alike: JUDGE_MAX_RETRIES for the same abandoned-worker reason as
    the llm-judge call, and the project's response deadline per attempt.

    Raises:
        Whatever UnifiedAiClient raises; every caller degrades it to -1.
    """
    sj = judge_config.similarity_judge
    return get_text_embedding(
        sj.provider, sj.model, text,
        max_response_timeout_seconds=judge_config.max_response_timeout_seconds,
        max_retries=JUDGE_MAX_RETRIES,
    )


def _evaluate_similarity(
    criteria: str,
    candidate_response: str,
    judge_config: JudgeConfig,
) -> JudgeScore:
    """Execute similarity evaluation using embedding cosine similarity.

    Args:
        criteria: Reference target text expected in the response.
        candidate_response: The response text generated by the candidate.
        judge_config: JudgeConfig instance.

    Returns:
        A tuple of (score, reasoning) where score is 1-10 scaled from the cosine similarity.
    """
    if not candidate_response.strip():
        return 1, "Empty candidate response. Score set to minimum (1)."
    if not criteria.strip():
        return 1, "Empty reference criteria/target response. Score set to minimum (1)."

    try:
        sim = cosine_similarity(
            embed_with_similarity_judge(candidate_response, judge_config),
            embed_with_similarity_judge(criteria, judge_config),
        )
        
        # Scale cosine similarity from 0.0-1.0 to 1-10
        clamped_sim = max(0.0, min(1.0, sim))
        score = int(round(1.0 + 9.0 * clamped_sim))
        score = max(1, min(10, score))
        
        reasoning = f"Cosine similarity between candidate response and target response is {sim:.4f}."
        return score, reasoning
    except Exception as exc:
        logger.log_error(f"Similarity evaluation failed: {exc}")
        return -1, f"Error: Similarity evaluation failed: {exc}"


def _evaluate_assert(
    criteria: str,
    candidate_response: str,
    judge_config: JudgeConfig,
) -> JudgeScore:
    """Execute evaluation using a vanilla Python assertion lambda.

    Args:
        criteria: String expression of a Python lambda function mapping response text to (score, reasoning).
        candidate_response: The response text generated by the candidate.
        judge_config: JudgeConfig instance, used only to reach the
            ``similarity_judge`` provider/model for the ``similarity`` helper.

    Returns:
        A tuple of (score, reasoning) evaluated from the lambda. The score is
        NOT clamped to 1-10: criteria are an unsandboxed lambda written by
        whoever owns the project directory, so keeping it in range (or using
        -1 to deliberately signal "not measured/not applicable") is their
        call, not the framework's. -1 is only returned on the framework's own
        initiative when it could not get a score out of the lambda at all
        (malformed syntax, a runtime exception, or a non-tuple return).

    The lambda is evaluated against an explicit namespace rather than this
    module's globals: it sees the single positional argument (the raw,
    unstripped candidate response), the stdlib modules ``re``, ``math``,
    ``json``, ``statistics``, ``datetime`` and ``string``, a
    ``similarity(a, b)`` helper (raw cosine of the two strings' embeddings via
    the configured ``similarity_judge``), a ``split_sentences(text)`` helper
    (the reasoning analysis's sentence splitter, returning strings), and the
    full Python builtins
    (``__import__`` included). This is not a sandbox: the criteria are trusted
    project-owned code. It just stops the lambda depending on whatever
    happened to be imported at module scope.
    """
    expr = criteria.strip()
    if not expr.startswith("lambda"):
        expr = f"lambda {expr}"

    def similarity(a: str, b: str) -> float:
        """Return the raw cosine similarity (in [-1.0, 1.0], not rescaled to
        1-10) between the embeddings of ``a`` and ``b``, computed with the
        project's ``similarity_judge`` provider/model. Performs a real
        embedding call; a backend failure raises and is caught below as a
        -1 "not measured" result."""
        return cosine_similarity(
            embed_with_similarity_judge(a, judge_config),
            embed_with_similarity_judge(b, judge_config),
        )

    def split_sentences(text: str) -> list[str]:
        """Return ``text`` split into sentences, exactly as the reasoning
        analysis splits a trace (reasoning.split_into_units: fenced code and
        headings stay atomic, short fragments merge into a neighbour, the
        parameters come from config.json's unit_splitting)."""
        # Lazy: reasoning imports this module, so a top-level import would cycle.
        from prompttestenv.reasoning import split_into_units
        return [text[a:b] for a, b in split_into_units(text)]

    namespace = {
        "__builtins__": __builtins__,
        "re": re,
        "math": math,
        "json": json,
        "statistics": statistics,
        "datetime": datetime,
        "string": string,
        "similarity": similarity,
        "split_sentences": split_sentences,
    }

    try:
        # Evaluate the lambda expression against the curated namespace.
        func = eval(expr, namespace)
        res = func(candidate_response)
        if isinstance(res, tuple) and len(res) == 2:
            score, reasoning = res
            return int(score), str(reasoning)
        else:
            return -1, f"Error: Assert lambda did not return a (score, reasoning) tuple. Got: {res}"
    except Exception as exc:
        return -1, f"Error: Assert evaluation failed: {exc}"


@dataclass
class TempPrompt:
    """Temporary prompt used to wrap global criteria text for LLM judge evaluations."""
    prompt: str
    criteria: str


def _side_provider(kind: str, judge_config: JudgeConfig) -> str | None:
    """Which provider one side of an evaluation will actually contact.

    Args:
        kind: A judge_type, or a global_criteria mode.
        judge_config: JudgeConfig instance.

    Returns:
        The provider name, or None when the side makes no call at all.
    """
    if kind == JUDGE_TYPE_LLM:
        return judge_config.test_judge.provider
    if kind == JUDGE_TYPE_SIMILARITY:
        return judge_config.similarity_judge.provider
    if kind == JUDGE_TYPE_ASSERT:
        # An assert lambda may call similarity() and embed through the same
        # judge, so it counts as reaching that provider.
        return judge_config.similarity_judge.provider
    return None


def _any_side_is_local(prompt, judge_config: JudgeConfig) -> bool:
    """Whether either side of this evaluation reaches a local backend.

    The gate used to read test_judge.provider alone, but that is only the
    judge the "llm-judge" evaluators use: "similarity" and "assert" embed
    through similarity_judge, whose default is ollama. A project judging with
    a remote test_judge and similarity criteria therefore looked remote and
    fired two concurrent embedding requests at the local backend, which is
    exactly what the sequential branch exists to prevent.

    Args:
        prompt: The TestCaseResult or TempPrompt being evaluated.
        judge_config: JudgeConfig instance.

    Returns:
        True if either the task or the global side is served locally.
    """
    sides = (
        _side_provider(getattr(prompt, "judge_type", JUDGE_TYPE_LLM), judge_config),
        _side_provider(getattr(judge_config.global_criteria, "mode", GLOBAL_MODE_NONE), judge_config),
    )
    return any(p and is_local_provider(p) for p in sides)


def evaluate_with_judge(
    prompt: TestCaseResult,
    candidate_response: str,
    judge_config: JudgeConfig,
    local_media_paths: list[str] | None = None,
) -> dict:
    """Run judge evaluation on a single candidate response.

    Calls the configured judge or calculates similarity/assert depending on the
    configured judge_type.

    Args:
        prompt: The TestCaseResult containing the original prompt and criteria.
        candidate_response: The LLM-generated text to evaluate.
        judge_config: JudgeConfig instance.
        local_media_paths: Optional local file paths to pass to the judge. Only
            the llm-judge evaluators take them; similarity and assert score the
            response text alone, by design.

    Returns:
        Dict with keys: score, reasoning, global_score, global_reasoning.
    """
    def _guard(side: str, evaluate):
        """Contain one side's failure to that side.

        The dispatcher's own except catches whatever escapes either evaluator
        and zeroes BOTH scores. In the parallel branch that threw away a global
        score already computed and paid for, and in the sequential branch the
        global side was never even attempted: the same fault produced two
        different outcomes depending on where the judge happened to run.
        """
        try:
            return evaluate()
        except Exception as exc:
            logger.log_error(f"{side} evaluation failed: {exc}")
            return -1, f"Error: {side} evaluation failed: {exc}"

    def run_task_eval():
        judge_type = getattr(prompt, "judge_type", JUDGE_TYPE_LLM)
        if judge_type == JUDGE_TYPE_LLM:
            return _evaluate_llm_judge(prompt, candidate_response, judge_config, local_media_paths)
        elif judge_type == JUDGE_TYPE_SIMILARITY:
            return _evaluate_similarity(prompt.criteria, candidate_response, judge_config)
        elif judge_type == JUDGE_TYPE_ASSERT:
            return _evaluate_assert(prompt.criteria, candidate_response, judge_config)
        else:
            return -1, f"Error: Unknown judge_type '{judge_type}'."

    def run_global_eval():
        g_criteria = judge_config.global_criteria
        g_mode = getattr(g_criteria, "mode", GLOBAL_MODE_NONE)
        if g_mode == GLOBAL_MODE_NONE:
            return -1, "N/A"
        elif g_mode == JUDGE_TYPE_LLM:
            mock_prompt = TempPrompt(prompt=prompt.prompt, criteria=g_criteria.llm_judge_criteria)
            return _evaluate_llm_judge(mock_prompt, candidate_response, judge_config, local_media_paths)
        elif g_mode == JUDGE_TYPE_SIMILARITY:
            return _evaluate_similarity(g_criteria.similarity_criteria, candidate_response, judge_config)
        elif g_mode == JUDGE_TYPE_ASSERT:
            return _evaluate_assert(g_criteria.assert_criteria, candidate_response, judge_config)
        else:
            return -1, f"Error: Unknown global evaluation mode '{g_mode}'."

    try:
        # A local backend serves one model at a time, so running the task and
        # global judges concurrently would only queue them against each other,
        # or force a second load into VRAM.
        if _any_side_is_local(prompt, judge_config):
            score, reasoning = _guard("Task", run_task_eval)
            global_score, global_reasoning = _guard("Global", run_global_eval)
            return {
                "score": score,
                "reasoning": reasoning,
                "global_score": global_score,
                "global_reasoning": global_reasoning,
            }

        with concurrent.futures.ThreadPoolExecutor(max_workers=2) as executor:
            future_task = executor.submit(_guard, "Task", run_task_eval)
            future_global = executor.submit(_guard, "Global", run_global_eval)
            score, reasoning = future_task.result()
            global_score, global_reasoning = future_global.result()

            return {
                "score": score,
                "reasoning": reasoning,
                "global_score": global_score,
                "global_reasoning": global_reasoning,
            }
    except Exception as exc:
        logger.log_error(f"Evaluation dispatcher failed: {exc}")
        return {
            "score": -1,
            "reasoning": f"Error: {str(exc)}",
            "global_score": -1,
            "global_reasoning": "Error",
        }

